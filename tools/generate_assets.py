"""Regenerate committed OpenGL/AOB assets offline, using only Python's standard library.

The reviewed visibility wrappers and baseline test fixture are maintained source.
No game binary, Cheat Engine, Lua runtime, or downloaded package is needed here.
"""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def assets():
    gl = json.loads((ROOT / "data/opengl-exports.json").read_text(encoding="utf-8"))["exports"]
    sites = json.loads((ROOT / "data/visibility-sites.json").read_text(encoding="utf-8"))
    assert len(gl) == 368 and len(sites) == 18
    assert len({x["name"] for x in gl}) == len({x["ordinal"] for x in gl}) == len(gl)
    output = {}
    output["opengl32.def"] = "LIBRARY opengl32\nEXPORTS\n" + "".join(
        f" {x['name']}=GL_Export_{i} @{x['ordinal']}\n" for i, x in enumerate(gl))
    header = ["/* Generated by tools/generate_assets.py; do not edit. */", f"#define GL_EXPORT_COUNT {len(gl)}"]
    header += [f"extern void GL_Lazy_{i}(void);" for i in range(len(gl))]
    header += [
        "FARPROC g_glFunctions[GL_EXPORT_COUNT]={" + ",".join(f"(FARPROC)GL_Lazy_{i}" for i in range(len(gl))) + "};",
        "static const char *g_glNames[GL_EXPORT_COUNT]={" + ",".join(json.dumps(x["name"]) for x in gl) + "};",
        "static const WORD g_glOrdinals[GL_EXPORT_COUNT]={" + ",".join(str(x["ordinal"]) for x in gl) + "};",
    ]
    output["gl_exports.inc"] = "\n".join(header) + "\n"
    asm = ["; Generated by tools/generate_assets.py; do not edit.", "option casemap:none",
           "EXTERN g_glFunctions:QWORD", "EXTERN ProxyInitialize:PROC", ".code",
           "PUBLIC ProxyResolve", "ProxyResolve PROC", "sub rsp,0C8h"]
    registers = [("rax", 0x20), ("rcx", 0x28), ("rdx", 0x30), ("r8", 0x38),
                 ("r9", 0x40), ("r10", 0x48), ("r11", 0x50)]
    asm += [f"mov [rsp+0{offset:X}h],{register}" for register, offset in registers]
    asm += [f"movdqu [rsp+0{0x60 + 16*i:X}h],xmm{i}" for i in range(6)]
    asm += ["call ProxyInitialize", "mov r11,[rsp+050h]", "lea r10,g_glFunctions", "mov r11,[r10+r11*8]"]
    asm += [f"movdqu xmm{i},[rsp+0{0x60 + 16*i:X}h]" for i in range(6)]
    asm += [f"mov {register},[rsp+0{offset:X}h]" for register, offset in registers[:-1]]
    asm += ["add rsp,0C8h", "jmp r11", "ProxyResolve ENDP"]
    for i in range(len(gl)):
        asm += [f"PUBLIC GL_Export_{i}", f"GL_Export_{i} PROC",
                f"jmp QWORD PTR [g_glFunctions+0{i*8:X}h]", f"GL_Export_{i} ENDP",
                f"PUBLIC GL_Lazy_{i}", f"GL_Lazy_{i} PROC", f"mov r11d,0{i:X}h",
                "jmp ProxyResolve", f"GL_Lazy_{i} ENDP"]
    output["gl_forwarders.asm"] = "\n".join(asm + ["END"]) + "\n"
    hooks = ["/* Generated AOB plan, baseline 645.348067. Do not edit. */", f"#define HOOK_COUNT {len(sites)}"]
    for i, site in enumerate(sites.values()):
        pattern = site["pattern"].split()
        window = bytes.fromhex(site["window"])
        offset = site["patch_offset"]
        assert len(pattern) == len(window) <= 64 and offset + 5 <= len(window)
        assert site["patch_length"] == 5 and window[offset] == 0xE8
        assert int(site["rva"], 16) + offset == int(site["patch_rva"], 16)
        target = int(site["patch_rva"], 16) + 5 + int.from_bytes(window[offset+1:offset+5], "little", signed=True)
        assert target == int(site["target_rva"], 16)
        assert all(token == "??" or int(token, 16) == byte for token, byte in zip(pattern, window))
        hooks += [f"static const BYTE pat_{i}[]={{" + ",".join("0" if x == "??" else "0x" + x for x in pattern) + "};",
                  f"static const BYTE mask_{i}[]={{" + ",".join("0" if x == "??" else "255" for x in pattern) + "};",
                  f"extern void HideHook_{i}(void);"]
    hooks += ["static const HookSpec g_specs[HOOK_COUNT]={"]
    for i, (name, site) in enumerate(sites.items()):
        hooks += ['{"%s",pat_%d,mask_%d,sizeof(pat_%d),%d,%s,(void*)HideHook_%d},' %
                  (name, i, i, i, site["patch_offset"], site["target_rva"], i)]
    output["hook_specs.inc"] = "\n".join(hooks + ["};"]) + "\n"
    wrappers = (ROOT / "src/asm/visibility_hooks.asm").read_text(encoding="utf-8")
    assert wrappers.count(" PROC\n") == len(sites)
    for i in range(len(sites)):
        assert f"HideHook_{i} PROC\n" in wrappers
    return output


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Check freshness without writing files")
    args = parser.parse_args()
    stale = []
    for name, content in assets().items():
        path = ROOT / "generated" / name
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != content:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8", newline="\n")
    if stale:
        parser.exit(1, "Stale assets: " + ", ".join(stale) + "; run python tools/generate_assets.py\n")
    print("Generated assets: " + ("fresh" if args.check else "updated") + "; 368 exports, 18 validated call sites")


if __name__ == "__main__":
    main()
